DROP TABLE IF EXISTS audit_logs, alerts, activity_events, ml_predictions,
csi_metadata, sessions, devices, rooms, roles, users, model_versions CASCADE;

-- 1. USERS
CREATE TABLE users (
    user_id UUID PRIMARY KEY,
    name VARCHAR(100) NOT NULL,
    email VARCHAR(150) UNIQUE NOT NULL,
    password_hash TEXT NOT NULL,
    status VARCHAR(20) DEFAULT 'Active',
    created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
);

-- 2. ROLES
CREATE TABLE roles (
    role_id UUID PRIMARY KEY,
    user_id UUID REFERENCES users(user_id),
    role_name VARCHAR(50) NOT NULL,
    description TEXT
);

-- 3. ROOMS
CREATE TABLE rooms (
    room_id UUID PRIMARY KEY,
    room_name VARCHAR(50) UNIQUE NOT NULL,
    room_type VARCHAR(50) NOT NULL,
    floor VARCHAR(20),
    status VARCHAR(20) DEFAULT 'Active',
    created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
);

-- 4. DEVICES
CREATE TABLE devices (
    device_id UUID PRIMARY KEY,
    room_id UUID NOT NULL REFERENCES rooms(room_id),
    device_name VARCHAR(100) NOT NULL,
    device_type VARCHAR(50) NOT NULL,
    mac_address VARCHAR(30) UNIQUE,
    ip_address VARCHAR(45),
    firmware_version VARCHAR(30),
    status VARCHAR(20) DEFAULT 'Online',
    installed_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
);

-- 5. MODEL VERSIONS
CREATE TABLE model_versions (
    model_version_id UUID PRIMARY KEY,
    model_name VARCHAR(100) NOT NULL,
    version VARCHAR(30) NOT NULL,
    algorithm VARCHAR(100),
    accuracy NUMERIC(5,2),
    trained_at TIMESTAMPTZ,
    status VARCHAR(20) DEFAULT 'Active',
    created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
);

-- 6. SESSIONS
CREATE TABLE sessions (
    session_id UUID PRIMARY KEY,
    device_id UUID NOT NULL REFERENCES devices(device_id),
    user_id UUID REFERENCES users(user_id),
    start_time TIMESTAMPTZ NOT NULL,
    end_time TIMESTAMPTZ,
    session_status VARCHAR(30) DEFAULT 'Active'
);

-- 7. CSI METADATA (Includes Amplitude and Phase Waveforms)
CREATE TABLE csi_metadata (
    csi_metadata_id UUID PRIMARY KEY,
    session_id UUID NOT NULL REFERENCES sessions(session_id),
    device_id UUID NOT NULL REFERENCES devices(device_id),
    room_id UUID NOT NULL REFERENCES rooms(room_id),
    capture_time TIMESTAMPTZ NOT NULL,
    center_frequency_ghz NUMERIC(6,3),
    channel_number INTEGER,
    bandwidth_mhz INTEGER,
    subcarriers INTEGER,
    sample_rate_hz INTEGER,
    packet_count INTEGER,
    rssi_dbm NUMERIC(6,2),
    amplitude_waveform DOUBLE PRECISION[],
    phase_waveform DOUBLE PRECISION[]
);

-- 8. ML PREDICTIONS
CREATE TABLE ml_predictions (
    prediction_id UUID PRIMARY KEY,
    csi_metadata_id UUID NOT NULL REFERENCES csi_metadata(csi_metadata_id),
    model_version_id UUID NOT NULL REFERENCES model_versions(model_version_id),
    predicted_movement VARCHAR(50) NOT NULL,
    confidence_score NUMERIC(5,2) CHECK (confidence_score BETWEEN 0 AND 100),
    prediction_time TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
);

-- 9. ACTIVITY EVENTS
CREATE TABLE activity_events (
    event_id UUID PRIMARY KEY,
    prediction_id UUID NOT NULL REFERENCES ml_predictions(prediction_id),
    session_id UUID NOT NULL REFERENCES sessions(session_id),
    room_id UUID NOT NULL REFERENCES rooms(room_id),
    event_type VARCHAR(50) NOT NULL,
    movement VARCHAR(50) NOT NULL,
    event_time TIMESTAMPTZ NOT NULL,
    duration_seconds INTEGER,
    severity VARCHAR(20) DEFAULT 'Normal'
);

-- 10. ALERTS
CREATE TABLE alerts (
    alert_id UUID PRIMARY KEY,
    event_id UUID NOT NULL REFERENCES activity_events(event_id),
    room_id UUID NOT NULL REFERENCES rooms(room_id),
    alert_type VARCHAR(50) NOT NULL,
    message TEXT NOT NULL,
    severity VARCHAR(20) NOT NULL,
    status VARCHAR(20) DEFAULT 'Open',
    created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
    acknowledged_by UUID REFERENCES users(user_id),
    acknowledged_at TIMESTAMPTZ
);

-- 11. AUDIT LOGS
CREATE TABLE audit_logs (
    audit_id UUID PRIMARY KEY,
    user_id UUID REFERENCES users(user_id),
    action VARCHAR(100) NOT NULL,
    table_name VARCHAR(100),
    record_id UUID,
    details TEXT,
    ip_address VARCHAR(45),
    created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
);

